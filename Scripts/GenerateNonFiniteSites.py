"""Generate the shared non-finite counter ABI and site identifiers from reviewed metadata."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


def symbol(site):
    return "NF_SITE_" + re.sub(r"[^A-Za-z0-9]", "_", site["id"]).upper()


def outputs(root):
    sites = json.loads((root / "Shaders/Metadata/NonFiniteSites.json").read_text(encoding="utf-8"))["sites"]
    identity = hashlib.sha256(json.dumps(sites, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
    low, high = int(identity[:8], 16), int(identity[8:16], 16)
    programs = sorted({program for site in sites for program in site["programs"]})
    hlsl = ["#pragma once", "", "// Generated by Scripts/GenerateNonFiniteSites.py from the reviewed site inventory."]
    hlsl += [f"static const uint {symbol(site)} = {index}u;" for index, site in enumerate(sites)]
    hlsl += [f"static const uint NF_SITE_COUNT = {len(sites)}u;", f"static const uint NF_PROGRAM_COUNT = {len(programs)}u;", ""]
    hlsl += [f"static const uint NF_INVENTORY_LOW = 0x{low:08x}u;", f"static const uint NF_INVENTORY_HIGH = 0x{high:08x}u;", ""]
    cpp = ['#pragma once', '#include "ShaderArtifactRuntime/ShaderProgramRegistry.h"', '', '#include <array>', '#include <cstdint>', '#include <string_view>', '', 'namespace gglab::nonfinite', '{',
           '\t// Generated by Scripts/GenerateNonFiniteSites.py; indices are private to this artifact ABI.',
           '\tinline constexpr uint32_t CounterBinding = 31;', '\tinline constexpr uint32_t CounterAbiVersion = 1;',
           '\tinline constexpr uint32_t CounterMagic = 0x4e464354;', '\tinline constexpr uint32_t HeaderBytes = 32;', '\tinline constexpr uint32_t RecordBytes = 32;',
           f'\tinline constexpr uint32_t SiteCount = {len(sites)};', f'\tinline constexpr uint32_t ProgramCount = {len(programs)};',
           '\tinline constexpr uint32_t BufferBytes = HeaderBytes + SiteCount * ProgramCount * RecordBytes;',
           '\tstruct Site { std::string_view m_Id; std::string_view m_NegativePolicy; std::string_view m_MaximumPolicy; };',
           '\tinline constexpr std::array Sites{']
    cpp.insert(15, f'\tinline constexpr uint32_t InventoryLow = 0x{low:08x};')
    cpp.insert(16, f'\tinline constexpr uint32_t InventoryHigh = 0x{high:08x};')
    cpp.insert(17, f'\tinline constexpr std::string_view VariantSuffix = ".nonfinite-counters.{identity}";')
    cpp += ['\t\tSite{ ' + ', '.join(json.dumps(x) for x in (site['id'], site['policy']['negative'], site['policy']['fp16Maximum'])) + ' },' for site in sites]
    cpp += ['\t};', '\tinline constexpr std::array<std::string_view, ProgramCount> Programs{']
    cpp += ['\t\t' + json.dumps(program) + ',' for program in programs]
    cpp += ['\t};', '\t[[nodiscard]] inline bool HasCounterVariant(const ShaderProgramRef& program) noexcept', '\t{',
            '\t\tif (program.m_Stage != ShaderStage::Pixel && program.m_Stage != ShaderStage::Compute)', '\t\t{', '\t\t\treturn false;', '\t\t}',
            '\t\tfor (const auto id : Programs)', '\t\t{', '\t\t\tif (program.m_ProgramId == id)', '\t\t\t{', '\t\t\t\treturn true;', '\t\t\t}', '\t\t}', '\t\treturn false;', '\t}',
            '\t[[nodiscard]] inline ShaderProgramRef CounterVariant(ShaderProgramRef program)', '\t{', '\t\tif (HasCounterVariant(program) && !program.m_VariantId.ends_with(VariantSuffix))', '\t\t{', '\t\t\tprogram.m_VariantId += VariantSuffix;', '\t\t}', '\t\treturn program;', '\t}', '}', '']
    return {root / 'Shaders/Common/NonFiniteSiteIds.hlsli': '\n'.join(hlsl), root / 'Sources/ShaderArtifactRuntime/Public/ShaderArtifactRuntime/NonFiniteCounterABI.h': '\n'.join(cpp)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, expected in outputs(args.root).items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != expected:
                print(f'Stale non-finite metadata: {path}', file=sys.stderr)
                return 1
        else:
            path.write_bytes(expected.replace('\n', '\r\n').encode('utf-8'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
